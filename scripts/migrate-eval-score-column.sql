-- without parsing anything. That was disclosed at the time. It is still
-- wrong in the way disclosed compromises are: a reader who does not know
-- about the encoding sees a populated `errorDetails` on an eval row and
-- reasonably reads it as a failure. ANY dashboard, alert, or ad-hoc query
-- filtering on `errorDetails IS NOT NULL` has been counting every successful
-- eval as an error since SCRUM-308 landed.
